# --- the other step tables keep their header -----------------------------------------------------

OTHER_STEPS = {
    "CP-2D": ("credit_snapshot", "Chart data: liquidity bridge"),
    "CP-4C": ("distressed_restructuring", "Chart data: value allocation — scenario 1"),
}
OLD = "| Step | Amount | Reporting unit | Basis and limitation |"
WITH_ID = "| Step | Amount | Add-Back ID | Reporting unit | Basis and limitation |"


@pytest.mark.parametrize("module", BRIDGE["other_step_tables_unchanged"]["modules"])
def test_other_step_tables_keep_the_old_header_in_the_request_and_the_check(tmp_path, module):
    pathway, heading = OTHER_STEPS[module]
    _, texts = all_instructions(_sub(tmp_path, "req"), pathway, modules=("CP-1", module))
    line = next((x for x in texts[module].splitlines() if x.startswith(f"- `### {heading}`")), "")
    assert line, f"{heading} is not asked for in {module}'s request"
    assert f"`{OLD}`" in line and "Add-Back ID" not in line

    prepared, task, context = good_task(tmp_path, module, pathway)
    base = answer(context, list(prepared.plan.layout.routes))
    check = checker(prepared.layout)
    assert _checked_handoff(task, base.encode(), check) == ()
    lines = base.split("\n")
    _, start, end = _span(lines, heading)
    assert lines[start] == OLD
    with_id = [
        WITH_ID,
        *(_row([*_cells(x)[:2], "Not applicable", *_cells(x)[2:]]) for x in lines[start + 1 : end]),
    ]
    lines[start:end] = with_id
    refused = _checked_handoff(task, "\n".join(lines).encode(), check)
    assert any(HEADER_REFUSAL in i and heading in i and f"`{OLD}`" in i for i in refused), refused


