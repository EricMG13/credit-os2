# --- helpers over the Markdown of a handoff -------------------------------------------------------


def _sub(tmp_path: Path, name: str) -> Path:
    folder = tmp_path / name
    folder.mkdir()
    return folder


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _drop(line: str, n: int) -> str:
    cells = _cells(line)
    return _row([c for at, c in enumerate(cells) if at != n])


def _span(lines: list[str], heading: str) -> tuple[int, int, int]:
    """The heading's line, the first and one past the last line of the table under it."""
    at = lines.index(f"### {heading}")
    start = at + 1
    while lines[start] == "":
        start += 1
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return at, start, end


def _replace_table(text: str, heading: str, table: list[str]) -> str:
    lines = text.split("\n")
    _, start, end = _span(lines, heading)
    lines[start:end] = table
    return "\n".join(lines)


def _put_section(text: str, table: list[str] | None) -> str:
    """The pro forma section set to `table` (None removes it): replaced when the answer has one,
    else inserted right after the Post-balance-sheet adjustments table."""
    lines = text.split("\n")
    if f"### {PF_HEADING}" in lines:
        at, start, end = _span(lines, PF_HEADING)
        if table is None:
            end += 1 if end < len(lines) and lines[end] == "" else 0
            del lines[at:end]
        else:
            lines[start:end] = table
    elif table is not None:
        _, _, end = _span(lines, POST_BS)
        lines[end:end] = ["", f"### {PF_HEADING}", "", *table]
    return "\n".join(lines)


def _variant(base: list[str], spec: dict) -> list[str]:
    """A refused variant's table, by the key's conventions (replace, replace_all, drop_column,
    header_without_unit)."""
    text = "\n".join(base)
    pairs = spec.get("replace_all") or ([spec["replace"]] if "replace" in spec else [])
    for old, new in pairs:
        assert old in text, (spec["name"], old)
        text = text.replace(old, new, 1)
    lines = text.split("\n")
    if "drop_column" in spec:
        lines = [lines[0], *(_drop(line, spec["drop_column"]) for line in lines[1:])]
    if spec.get("header_without_unit"):
        at = _cells(lines[0]).index("Reporting unit")
        lines = [_drop(line, at) for line in lines]
    return lines


