def test_a_cp1_response_retained_before_this_pr_is_refused_on_replay(tmp_path, cp1):
    """The tightened-checker contract (cpos.py `_handoff`, `cpos_retained_rejected`): the helper's
    good answer with the old bridge header and no pro forma section."""
    base, _, task = cp1
    old = _replace_table(base, BRIDGE_HEADING, OLD_STATED)
    retained = _put_section(old, None)
    prepared, _, _ = good_task(_sub(tmp_path, "again"), "CP-1", "credit_snapshot")

    def execute(_task):
        pytest.fail("a retained response is replayed, never sent again")

    with pytest.raises(ValueError, match="cpos_retained_rejected: CP-1") as raised:
        cpos._handoff(
            task,
            tmp_path / "replay",
            execute,
            checker(prepared.layout),
            1,
            retained=retained.encode(),
        )
    message = str(raised.value)
    assert BRIDGE_HEADING in message and BRIDGE["new_header"] in message
    assert PF_HEADING in message


