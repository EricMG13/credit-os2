# --- the issuer library's reading of the bridge --------------------------------------------------


def _library(table: list[str]) -> dict:
    text = "## Findings\n\n### " + BRIDGE_HEADING + "\n\n" + "\n".join(table) + "\n"
    return store.reader_fields(store.sections_of(text))


def _bridge_chart(fields: dict) -> dict:
    (chart,) = [c for c in fields["charts"] if c.get("kind") == "waterfall"]
    return chart


def _library_shape(chart: dict) -> dict:
    return {k: chart[k] for k in ("kind", "amount", "columns", "unit")}


def test_the_library_reads_the_synthetic_new_header_bridge():
    reading = BRIDGE["reading"]["synthetic_new_header"]
    fields = _library(BRIDGE["accepted"]["stated"])
    assert fields["issue"] is None, fields["issue"]
    assert _library_shape(_bridge_chart(fields)) == reading["library"]


def test_the_library_reads_the_same_rows_under_the_old_header_the_same_way():
    reading = BRIDGE["reading"]["synthetic_new_header"]
    fields = _library(OLD_STATED)
    assert fields["issue"] is None, fields["issue"]
    assert _library_shape(_bridge_chart(fields)) == reading["library"]


@pytest.mark.parametrize("header", ["new", "old"])
def test_the_library_gives_the_stated_reason_of_an_all_gap_bridge(header):
    table = BRIDGE["accepted"]["all_gap"]
    if header == "old":
        table = [table[0].replace(" Add-Back ID |", ""), *(_drop(x, 2) for x in table[1:])]
    fields = _library(table)
    assert fields["issue"] is None, fields["issue"]
    assert fields["charts"] == []
    (gap,) = fields["chartGaps"]
    assert gap["gap"] == BRIDGE["reading"]["synthetic_all_gap_new_header"]["gap"]


def test_the_library_reads_the_retained_replay_to_the_hand_values():
    reading = BRIDGE["reading"]["retained_replay_old_header"]
    text = (ROOT / reading["file"]).read_text(encoding="utf-8")
    sections = store.sections_of(text)
    chart = _bridge_chart(store.reader_fields(sections))
    assert _library_shape(chart) == reading["library"]
    (section,) = [s for s in sections if s["heading"] == BRIDGE_HEADING]
    (table,) = [b for b in section["blocks"] if b["type"] == "table"]
    rows = [r["cells"] for r in table["rows"]]
    assert [r[0] for r in rows] == reading["labels"]
    assert [r[chart["amount"]] for r in rows] == reading["amounts"]


